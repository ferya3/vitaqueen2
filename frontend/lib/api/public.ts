import "server-only";
import { cacheLife, cacheTag } from "next/cache";
import type { Locale } from "@/lib/i18n/config";
import type {
  Article,
  Category,
  Certificate,
  HomePayload,
  Page,
  Paginated,
  Product,
  ProductionLine,
  ProductionStep,
  SiteSettings,
} from "@/types/api";

/**
 * Public content API.
 *
 * Every function is cached with `'use cache'` (profile "content", see next.config.ts)
 * and tagged "content". Laravel calls POST /api/revalidate whenever editors change
 * content, so pages update within seconds without rebuilding.
 *
 * If the API is unreachable (e.g. `next build` without a running backend) the
 * functions fall back to the committed snapshot in data/snapshot — generated by
 * `npm run snapshot`. A real 404 from the API is never replaced by the snapshot.
 */

const API_URL = (process.env.API_INTERNAL_URL ?? process.env.NEXT_PUBLIC_API_URL ?? "http://localhost:8000/api/v1").replace(/\/$/, "");

type Snapshot = {
  home: HomePayload;
  settings: SiteSettings;
  categories: Category[];
  products: Product[];
  productDetails: Record<string, { data: Product; related: Product[] }>;
  articles: Paginated<Article>;
  articleDetails: Record<string, { data: Article; related: Article[] }>;
  certificates: Certificate[];
  productionLines: ProductionLine[];
  productionSteps: ProductionStep[];
  pages: Record<string, Page>;
  sitemap: { products: { slug: string; updated_at: string }[]; articles: { slug: string; updated_at: string }[] };
};

class NotFoundError extends Error {}

async function loadSnapshot(locale: Locale): Promise<Snapshot | null> {
  try {
    return (await import(`@/data/snapshot/${locale}.json`)).default as Snapshot;
  } catch {
    return null;
  }
}

async function request<T>(path: string, locale: Locale): Promise<T> {
  const url = `${API_URL}${path}${path.includes("?") ? "&" : "?"}locale=${locale}`;
  const res = await fetch(url, {
    headers: { Accept: "application/json", "Accept-Language": locale },
    signal: AbortSignal.timeout(10_000),
  });
  if (res.status === 404) throw new NotFoundError(path);
  if (!res.ok) throw new Error(`API ${res.status} for ${path}`);
  return (await res.json()) as T;
}

/** Fetch from the API; on network / server failure use the snapshot. 404 -> null. */
async function withFallback<T>(locale: Locale, path: string, pick: (s: Snapshot) => T | undefined): Promise<T | null> {
  try {
    return await request<T>(path, locale);
  } catch (error) {
    if (error instanceof NotFoundError) return null;
    const snapshot = await loadSnapshot(locale);
    const value = snapshot ? pick(snapshot) : undefined;
    if (value === undefined) {
      console.error(`[api] ${path} failed and no snapshot is available`, error);
      throw error;
    }
    console.warn(`[api] ${path} unavailable, serving snapshot (${(error as Error).message})`);
    return value;
  }
}

function tagContent() {
  cacheLife("content");
  cacheTag("content");
}

export async function getHome(locale: Locale): Promise<HomePayload> {
  "use cache";
  tagContent();
  const res = await withFallback<{ data: HomePayload }>(locale, "/home", (s) => ({ data: s.home }));
  return res!.data;
}

export async function getSettings(locale: Locale): Promise<SiteSettings> {
  "use cache";
  tagContent();
  const res = await withFallback<{ data: SiteSettings }>(locale, "/settings", (s) => ({ data: s.settings }));
  return res!.data;
}

