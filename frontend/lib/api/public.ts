export async function getPage(locale: Locale, slug: string): Promise<Page | null> {
  "use cache";
  tagContent();
  const res = await withFallback<{ data: Page }>(locale, `/pages/${encodeURIComponent(slug)}`, (s) =>
    s.pages[slug] ? { data: s.pages[slug] } : undefined,
  );
  return res?.data ?? null;
}

export async function getSitemapData(): Promise<Snapshot["sitemap"]> {
  "use cache";
  tagContent();
  const res = await withFallback<{ data: Snapshot["sitemap"] }>("fa", "/sitemap", (s) => ({ data: s.sitemap }));
  return res!.data;
}
