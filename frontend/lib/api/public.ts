export async function getProduct(locale: Locale, slug: string): Promise<{ data: Product; related: Product[] } | null> {
  "use cache";
  tagContent();
  return withFallback(locale, `/products/${encodeURIComponent(slug)}`, (s) => s.productDetails[slug] ?? undefined);
}

export async function getArticles(locale: Locale, page = 1, type?: "news" | "article"): Promise<Paginated<Article>> {
  "use cache";
  tagContent();
  const query = `?page=${page}&per_page=9${type ? `&type=${type}` : ""}`;
  const res = await withFallback<Paginated<Article>>(locale, `/articles${query}`, (s) =>
    page === 1 && !type ? s.articles : { data: [], meta: { current_page: page, last_page: 1, per_page: 9, total: 0 } },
  );
  return res!;
}

